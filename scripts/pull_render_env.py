#!/usr/bin/env python3
"""Pull MindMate env vars from Render into a local .env (gitignored).

Requires RENDER_API_KEY. Useful when free Render hours are exhausted and the
bot must run in local polling mode.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

try:
    import requests
except ImportError:
    print("Install requests first: pip install requests", file=sys.stderr)
    raise SystemExit(1)

# Production + staging MindMate workers (from Render dashboard / suspension email)
DEFAULT_SERVICE_IDS = (
    "srv-d62nnqkr85hc739oc0kg",  # mindmate
    "srv-d61nle4oud1c73aggvf0",  # mindmate-dev
)

KEEP_KEYS = {
    "TELEGRAM_BOT_TOKEN",
    "MINDMATE_OPENROUTER_API_KEY",
    "MINDMATE_OPENROUTER_CHAT_MODEL",
    "DATABASE_URL",
    "NEON_MINDMATE_DB_URL",
    "DAILY_HEARTBEAT_ENABLED",
    "DAILY_HEARTBEAT_HOUR",
    "DAILY_HEARTBEAT_WINDOW_MINUTES",
    "DAILY_HEARTBEAT_POLL_SECONDS",
    "DAILY_HEARTBEAT_TIMEZONE",
    "DAILY_HEARTBEAT_ALLOWED_USER_IDS",
    "DAILY_HEARTBEAT_CHAT_ID",
    "DAILY_HEARTBEAT_MESSAGE_THREAD_ID",
    "AUTO_WEB_SEARCH_ENABLED",
    "REDIS_URL",
}

# Both are required for a usable bot; database and heartbeat settings are optional.
REQUIRED_KEYS = ("TELEGRAM_BOT_TOKEN", "MINDMATE_OPENROUTER_API_KEY")


def fetch_env_vars(api_key: str, service_id: str) -> dict[str, str]:
    headers = {"Authorization": f"Bearer {api_key}", "Accept": "application/json"}
    url = f"https://api.render.com/v1/services/{service_id}/env-vars"
    resp = requests.get(url, headers=headers, timeout=30)
    if resp.status_code != 200:
        # Render error bodies may contain sensitive configuration.
        raise RuntimeError(f"{service_id}: HTTP {resp.status_code}")

    payload = resp.json()
    # Render returns either a bare list or objects with {"envVar": {...}}
    items = payload if isinstance(payload, list) else payload.get("envVars") or payload.get("env_vars") or []
    out: dict[str, str] = {}
    for item in items:
        env = item.get("envVar", item) if isinstance(item, dict) else {}
        key = env.get("key")
        value = env.get("value")
        if key and value is not None and key in KEEP_KEYS:
            out[key] = str(value)
    return out


def write_env(path: Path, values: dict[str, str]) -> None:
    # Never write RENDER_EXTERNAL_URL — local mode must use Telegram polling.
    lines = [
        "# Generated by scripts/pull_render_env.py — do not commit",
        "# RENDER_EXTERNAL_URL intentionally omitted (polling mode)",
        "",
    ]
    for key in sorted(values):
        # Escape newlines; keep simple KEY=value
        val = values[key].replace("\n", "\\n")
        lines.append(f"{key}={val}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    try:
        os.chmod(path, 0o600)
    except OSError:
        pass


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--service-id",
        action="append",
        dest="service_ids",
        help="Render service id (repeatable, ordered fallbacks; never merged). "
        "Default: mindmate then mindmate-dev. Specify one id to pin an environment.",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=Path(__file__).resolve().parent.parent / ".env",
        help="Output .env path (default: project root .env)",
    )
    args = parser.parse_args()

    api_key = os.environ.get("RENDER_API_KEY", "").strip()
    if not api_key:
        print("RENDER_API_KEY is not set.", file=sys.stderr)
        return 1

    service_ids = args.service_ids or list(DEFAULT_SERVICE_IDS)
    for service_id in service_ids:
        try:
            fetched = fetch_env_vars(api_key, service_id)
        except Exception as exc:  # noqa: BLE001 — try the next complete configuration
            # Do not expose response bodies, request headers, or exception secrets.
            print(f"SKIP {service_id}: fetch failed ({type(exc).__name__})", file=sys.stderr)
            continue

        missing = [key for key in REQUIRED_KEYS if not fetched.get(key, "").strip()]
        if missing:
            print(f"SKIP {service_id}: missing {', '.join(missing)}", file=sys.stderr)
            continue

        # Select the entire first usable service, including only its optional keys.
        # Never fill gaps from another service, the old .env, or the process env.
        write_env(args.out, fetched)
        print(f"Wrote {args.out} from {service_id} ({len(fetched)} keys). "
              "Start with: bash scripts/run_local.sh")
        return 0

    print("No service supplied a complete configuration; output left unchanged.", file=sys.stderr)
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
